#!/usr/bin/env bash
# Regenerates cef-sys/src/bindings_156.rs (CEF 156, x86_64) from the CEF binary distribution.
#
# usage: utils/gen_bindings_156.sh <cef_binary_156..._windows64 dir> [libclang dir]
#
# Needs bindgen-cli 0.72 and libclang >= 15 (e.g. `pip install libclang==18.1.1`, then point
# the second argument at site-packages/clang/native).
set -euo pipefail

CEF_DIR="$1"
if [ $# -ge 2 ]; then export LIBCLANG_PATH="$2"; fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/cef-sys/src/bindings_156.rs"
TMP="$(mktemp)"

bindgen "$ROOT/utils/wrapper156.h" -o "$TMP" \
    --default-enum-style=moduleconsts \
    --allowlist-type 'cef_.*' --allowlist-function 'cef_.*' --allowlist-var 'CEF_.*' \
    --bitfield-enum '.*_mask_t' \
    -- -I "$CEF_DIR" -DCEF_API_VERSION=15600 --target=x86_64-pc-windows-msvc

{
    echo "/* CEF 156.0.15 (Chromium 156), CEF_API_VERSION=15600, x86_64-pc-windows-msvc."
    echo "   Generated by utils/gen_bindings_156.sh (bindgen 0.72.1). Do not edit by hand. */"
    # The cef crate declares callbacks as extern \"system\" (stdcall on 32-bit). On x86_64
    # \"system\" and \"C\" are the same ABI, so align the types with the 32-bit bindings.
    sed 's/extern "C"/extern "system"/g' "$TMP"
} > "$OUT"

rm -f "$TMP"
echo "written $OUT"
